package v1alpha1

import (
	corev1 "k8s.io/api/core/v1"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
)

// ResourceTier defines the size of the environment
// +kubebuilder:validation:Enum=small;medium;large
type ResourceTier string

// DatabaseSpec configures the ephemeral PostgreSQL sidecar
type DatabaseSpec struct {
	// Enabled controls whether a PostgreSQL instance is provisioned alongside the app
	// +kubebuilder:default=false
	Enabled bool `json:"enabled,omitempty"`

	// Version is the PostgreSQL major version to use (e.g. "15", "16")
	// +kubebuilder:default="15"
	// +optional
	Version string `json:"version,omitempty"`

	// DatabaseName is the logical database created inside PostgreSQL
	// +kubebuilder:default="appdb"
	// +optional
	DatabaseName string `json:"databaseName,omitempty"`

	// Migration configures an optional one-shot Job that runs before the app is deployed.
	// The operator injects POSTGRES_USER, POSTGRES_PASSWORD, POSTGRES_DB and DATABASE_URL.
	// +optional
	Migration *DatabaseTaskSpec `json:"migration,omitempty"`

	// Seed configures an optional one-shot Job that runs after migration and before the app is deployed.
	// The operator injects POSTGRES_USER, POSTGRES_PASSWORD, POSTGRES_DB and DATABASE_URL.
	// +optional
	Seed *DatabaseTaskSpec `json:"seed,omitempty"`
}

// DatabaseTaskSpec configures a one-shot database task.
type DatabaseTaskSpec struct {
	// Enabled controls whether this database task is executed.
	// +kubebuilder:default=false
	// +optional
	Enabled bool `json:"enabled,omitempty"`

	// Image is the container image used to run the task. When empty, spec.image is used.
	// +optional
	Image string `json:"image,omitempty"`

	// Command is the entrypoint command for the task.
	// +optional
	Command []string `json:"command,omitempty"`

	// Args are optional arguments passed to the command.
	// +optional
	Args []string `json:"args,omitempty"`
}

// TelemetryLanguage defines the OpenTelemetry auto-instrumentation language.
// +kubebuilder:validation:Enum=python;java;nodejs;dotnet;go;sdk
type TelemetryLanguage string

const (
	TierSmall  ResourceTier = "small"
	TierMedium ResourceTier = "medium"
	TierLarge  ResourceTier = "large"
)

const (
	TelemetryLanguagePython TelemetryLanguage = "python"
	TelemetryLanguageJava   TelemetryLanguage = "java"
	TelemetryLanguageNodeJS TelemetryLanguage = "nodejs"
	TelemetryLanguageDotNet TelemetryLanguage = "dotnet"
	TelemetryLanguageGo     TelemetryLanguage = "go"
	TelemetryLanguageSDK    TelemetryLanguage = "sdk"
)

// AutoInstrumentationSpec configures OpenTelemetry Operator auto-instrumentation
// for the application Pod.
type AutoInstrumentationSpec struct {
	// Language is the runtime to auto-instrument.
	// +kubebuilder:validation:Required
	Language TelemetryLanguage `json:"language"`

	// InstrumentationRef is the Instrumentation resource used by the OpenTelemetry Operator.
	// It can be "true", a name in the app namespace, or "namespace/name".
	// When empty, the controller uses "true".
	// +optional
	InstrumentationRef string `json:"instrumentationRef,omitempty"`

	// PythonPlatform selects the Python auto-instrumentation platform.
	// Use "musl" for Alpine-based Python images when supported by the OpenTelemetry Operator.
	// +kubebuilder:validation:Enum=glibc;musl
	// +optional
	PythonPlatform string `json:"pythonPlatform,omitempty"`

	// GoTargetExecutable is required by OpenTelemetry Go auto-instrumentation.
	// It must point to the executable inside the application container.
	// +optional
	GoTargetExecutable string `json:"goTargetExecutable,omitempty"`
}

// TelemetrySpec configures application observability wiring generated by the operator.
type TelemetrySpec struct {
	// Enabled controls whether telemetry settings are added to the app Pod template.
	// +kubebuilder:default=false
	Enabled bool `json:"enabled,omitempty"`

	// ServiceName sets OTEL_SERVICE_NAME for the application.
	// When empty, the controller uses "cellenza-<resource-name>".
	// +optional
	ServiceName string `json:"serviceName,omitempty"`

	// AutoInstrumentation configures OpenTelemetry Operator auto-instrumentation.
	// +optional
	AutoInstrumentation *AutoInstrumentationSpec `json:"autoInstrumentation,omitempty"`
}

// GitHubTokenSecretRef points to a Secret containing a GitHub token.
type GitHubTokenSecretRef struct {
	// Name is the Secret name.
	// +kubebuilder:validation:MinLength=1
	Name string `json:"name"`

	// Namespace is the Secret namespace. When empty, the controller namespace is used.
	// +optional
	Namespace string `json:"namespace,omitempty"`

	// Key is the Secret data key containing the token. Defaults to "token".
	// +optional
	Key string `json:"key,omitempty"`
}

// GitHubIntegrationSpec configures GitHub Deployment and pull request updates
// emitted by the controller once it observes the preview environment state.
type GitHubIntegrationSpec struct {
	// Enabled controls whether the controller sends updates to GitHub.
	// +kubebuilder:default=false
	Enabled bool `json:"enabled,omitempty"`

	// Owner is the GitHub repository owner or organization.
	// +optional
	Owner string `json:"owner,omitempty"`

	// Repo is the GitHub repository name.
	// +optional
	Repo string `json:"repo,omitempty"`

	// DeploymentID is the GitHub Deployment id to update.
	// +optional
	DeploymentID int64 `json:"deploymentId,omitempty"`

	// Environment is the GitHub Deployment environment name (for example "pr-42").
	// +optional
	Environment string `json:"environment,omitempty"`

	// TokenSecretRef points to a Secret containing a GitHub token.
	// +optional
	TokenSecretRef *GitHubTokenSecretRef `json:"tokenSecretRef,omitempty"`

	// CommentOnReady controls whether the controller comments on the PR when the preview is ready.
	// +kubebuilder:default=false
	// +optional
	CommentOnReady bool `json:"commentOnReady,omitempty"`
}

// EnvironmentPhase describes the lifecycle phase
type EnvironmentPhase string

const (
	PhasePending      EnvironmentPhase = "Pending"
	PhaseProvisioning EnvironmentPhase = "Provisioning"
	PhaseRunning      EnvironmentPhase = "Running"
	PhaseTerminating  EnvironmentPhase = "Terminating"
	PhaseFailed       EnvironmentPhase = "Failed"
)

// CellenzaSpec defines the desired state
type CellenzaSpec struct {
	// Branch is the git branch name for this preview environment
	// +kubebuilder:validation:MinLength=1
	Branch string `json:"branch"`

	// PRNumber is the pull request number
	PRNumber int `json:"prNumber"`

	// Image is the container image to deploy
	// +kubebuilder:validation:MinLength=1
	Image string `json:"image"`

	// TTL is the time-to-live duration (e.g. "48h", "24h", "72h")
	// +kubebuilder:validation:Pattern=`^[0-9]+(h|m)$`
	// +kubebuilder:default="48h"
	TTL string `json:"ttl,omitempty"`

	// ResourceTier controls CPU/Memory quotas
	// +kubebuilder:default=medium
	ResourceTier ResourceTier `json:"resourceTier,omitempty"`

	// RequiresApproval blocks provisioning until ApprovedBy is set
	// +kubebuilder:default=false
	RequiresApproval bool `json:"requiresApproval,omitempty"`

	// ApprovedBy is the user who approved this environment (required when RequiresApproval=true)
	// +optional
	ApprovedBy string `json:"approvedBy,omitempty"`

	// Replicas for the preview deployment
	// +kubebuilder:default=1
	// +kubebuilder:validation:Minimum=1
	// +kubebuilder:validation:Maximum=5
	Replicas int32 `json:"replicas,omitempty"`

	// Database configures an ephemeral PostgreSQL instance for this environment
	// +optional
	Database *DatabaseSpec `json:"database,omitempty"`

	// Telemetry configures application observability integration.
	// +optional
	Telemetry *TelemetrySpec `json:"telemetry,omitempty"`

	// GitHub configures optional GitHub Deployment and pull request updates.
	// +optional
	GitHub *GitHubIntegrationSpec `json:"github,omitempty"`
}

// GitHubIntegrationStatus describes the latest GitHub notification emitted by the controller.
type GitHubIntegrationStatus struct {
	// DeploymentState is the last GitHub Deployment state sent by the controller.
	// +optional
	DeploymentState string `json:"deploymentState,omitempty"`

	// LastNotifiedPhase is the Cellenza phase corresponding to the last notification.
	// +optional
	LastNotifiedPhase EnvironmentPhase `json:"lastNotifiedPhase,omitempty"`

	// LastEnvironmentURL is the URL sent to GitHub.
	// +optional
	LastEnvironmentURL string `json:"lastEnvironmentUrl,omitempty"`

	// CommentID is the GitHub issue comment id created for the PR.
	// +optional
	CommentID int64 `json:"commentId,omitempty"`

	// LastError stores the latest non-blocking GitHub notification error.
	// +optional
	LastError string `json:"lastError,omitempty"`

	// LastNotifiedAt is when the latest GitHub notification was sent.
	// +optional
	LastNotifiedAt *metav1.Time `json:"lastNotifiedAt,omitempty"`
}

// CellenzaStatus defines the observed state
type CellenzaStatus struct {
	// Phase is the current lifecycle phase
	Phase EnvironmentPhase `json:"phase,omitempty"`

	// URL is the ingress URL of the preview environment
	URL string `json:"url,omitempty"`

	// NamespaceName is the dedicated namespace created for this env
	NamespaceName string `json:"namespaceName,omitempty"`

	// ExpiresAt is when this environment will be auto-deleted
	ExpiresAt *metav1.Time `json:"expiresAt,omitempty"`

	// Conditions represent the latest available observations
	Conditions []metav1.Condition `json:"conditions,omitempty"`

	// ObservedGeneration helps detect spec changes
	ObservedGeneration int64 `json:"observedGeneration,omitempty"`

	// DatabaseSecretName is the name of the Secret holding PostgreSQL credentials (when database is enabled)
	// +optional
	DatabaseSecretName string `json:"databaseSecretName,omitempty"`

	// Database describes the observed PostgreSQL and database task state.
	// +optional
	Database *DatabaseStatus `json:"database,omitempty"`

	// Diagnostics describes the latest operator-generated troubleshooting summary.
	// +optional
	Diagnostics *DiagnosticsStatus `json:"diagnostics,omitempty"`

	// GitHub describes the latest GitHub Deployment or PR notification.
	// +optional
	GitHub *GitHubIntegrationStatus `json:"github,omitempty"`
}

