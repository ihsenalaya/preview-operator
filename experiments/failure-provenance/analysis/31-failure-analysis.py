#!/usr/bin/env python3
"""
31-failure-analysis.py — Cross-subject failure-mode synthesis for F5, F9, F10.

Reviewer critique #3: the article needs an explicit failure analysis on the
scenarios where the system underperforms (F5, F9, F10), explaining *why* — not
just stating the 0/0.0 % cells.

Reads the 15 qualitative case-study cards
(`docs/research/failure-provenance/analysis-output/26-qualitative/s*-F{5,9,10}.md`)
and emits a structured markdown synthesis grouped by failure-mode family:

  C-a  contract-test shadowing       (F5)
  C-b  vocabulary mismatch           (F10)
  C-c  symptom-blaming on multi-fault (F9)
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
CARDS = REPO / "docs/research/failure-provenance/analysis-output/26-qualitative"
OUT = REPO / "docs/research/failure-provenance/analysis-output/31-failure-analysis"
OUT.mkdir(parents=True, exist_ok=True)


def parse_card(path: Path) -> dict:
    """Pull (ground-truth, LLM-A, LLM-B) tuples from a qualitative card."""
    txt = path.read_text(errors="ignore")
    out = {"path": path, "subject": path.stem.rsplit("-", 1)[0],
           "scenario": path.stem.rsplit("-", 1)[1]}

    # Ground truth from header line: **Ground truth:** component=`X` category=`Y`
    m = re.search(r"\*\*Ground truth:\*\*\s*component=`([^`]+)`\s*category=`([^`]+)`", txt)
    if m:
        out["gt_component"] = m.group(1)
        out["gt_category"] = m.group(2)

    # LLM-A and LLM-B blocks: extract component, category, cause
    for tag in ("LLM-A", "LLM-B"):
        block_match = re.search(
            rf"### {tag}\s*\n\n- component: `([^`]+)`\s*\n- category:\s*`([^`]+)`\s*\n- cause:\s*(.*?)(?:\n\n|$)",
            txt, re.DOTALL,
        )
        if block_match:
            out[f"{tag.lower().replace('-','_')}_component"] = block_match.group(1).strip()
            out[f"{tag.lower().replace('-','_')}_category"] = block_match.group(2).strip()
            cause = block_match.group(3).strip()
            cause = re.sub(r"\s+", " ", cause)[:240]
            out[f"{tag.lower().replace('-','_')}_cause"] = cause

    # Bundle size + evidence count
    m = re.search(r"\*\*Bundle size:\*\*\s*(\d+)\s*bytes", txt)
    if m:
        out["bundle_size"] = int(m.group(1))

    return out


def family(scenario: str) -> str:
    return {
        "F5": "C-a contract-test shadowing",
        "F9": "C-c symptom-blaming on multi-fault",
        "F10": "C-b vocabulary mismatch",
    }.get(scenario, "?")


def category_match(diag_cat: str, gt_cat: str) -> str:
    if not diag_cat or not gt_cat:
        return "?"
    d = diag_cat.strip().lower()
    g = gt_cat.strip().lower()
    if d == g:
        return "✅"
    return "❌"


def main() -> int:
    cards = sorted(CARDS.glob("s*-F{5,9,10}.md"))
    if not cards:
        # fall back to explicit glob
        cards = sorted([p for p in CARDS.glob("s*-*.md")
                        if any(p.stem.endswith(s) for s in ("-F5", "-F9", "-F10"))])
    if not cards:
        print("no F5/F9/F10 cards found", file=sys.stderr)
        return 1
    parsed = [parse_card(p) for p in cards]

    md = [
        "# Failure analysis on F5, F9, F10 — cross-subject synthesis",
        "",
        f"Reads the {len(parsed)} qualitative case-study cards covering F5 / F9 / F10 ",
        "across the five reference applications and groups the diagnostic failures ",
        "into three named families:",
        "",
        "| Family | Scenario | Symptom |",
        "|---|---|---|",
        "| **C-a contract-test shadowing** | F5 (frontend HTML id) | A downstream contract test fails simultaneously with the upstream frontend break; the diagnoser blames the API. |",
        "| **C-b vocabulary mismatch** | F10 (flaky test) | The diagnoser names the right *family* (`test-suite`, `e2e`) but uses a synonym the alias matcher does not credit. |",
        "| **C-c symptom-blaming on multi-fault** | F9 (bad seed data) | Multiple downstream tests fail; the diagnoser names a symptom-bearing pod (e.g. `e2e-tests`) rather than the upstream seed job. |",
        "",
        "Each card is a single representative rep (`r1`) from the matrix; the other ",
        "9 reps per cell are tabulated in `results-augmented.csv` and ",
        "`results-multiapp/runs.csv`. Reproducibility: cards generated by ",
        "`experiments/failure-provenance/analysis/26-qualitative.py`.",
        "",
        "## Per-scenario, per-subject diagnoses (verbatim from C5 cards)",
        "",
    ]

    # Group by scenario family
    for scenario in ("F5", "F9", "F10"):
        cs = [c for c in parsed if c.get("scenario") == scenario]
        if not cs:
            continue
        family_name = family(scenario)
        md.append(f"### {family_name} — {scenario}")
        md.append("")
        # Use the first one's ground truth for the header (consistent per scenario).
        gt_c = cs[0].get("gt_component", "?")
        gt_cat = cs[0].get("gt_category", "?")
        md.append(f"**Ground truth (rubric):** component=`{gt_c}`, category=`{gt_cat}`.")
        md.append("")
        md.append("| Subject | LLM-A component / category | LLM-A cat ✓? | LLM-B component / category | LLM-B cat ✓? |")
        md.append("|---|---|:---:|---|:---:|")
        for c in cs:
            ac = c.get("llm_a_component", "—")
            acc = c.get("llm_a_category", "—")
            bc = c.get("llm_b_component", "—")
            bcc = c.get("llm_b_category", "—")
            md.append(
                f"| `{c['subject']}` | `{ac}` / `{acc}` | "
                f"{category_match(acc, gt_cat)} | "
                f"`{bc}` / `{bcc}` | "
                f"{category_match(bcc, gt_cat)} |"
            )
        md.append("")
        # A short narrative per family.
        if scenario == "F5":
            md += [
                "**Why this fails.** The injected fault changes the frontend's HTML element ",
                "id, breaking the e2e Playwright test. The contract test against the backend ",
                "API also fails because the test runs `/api/submit` which catches the frontend ",
                "regression downstream. Both LLMs and the rule diagnoser see the contract ",
                "failure first and rank it above the e2e failure. Result: the *category* is ",
                "often right (`application`) but the *component* is `API` instead of ",
                "`frontend`. The aligned matcher refuses to credit this (otherwise we would ",
                "have to credit `API` on every backend bug, which would inflate every other ",
                "scenario). The fix is in the diagnoser's ranking, not the bundle.",
                "",
            ]
        elif scenario == "F10":
            md += [
                "**Why this fails — and why this is not a diagnostic failure.** The injected ",
                "fault adds a long sleep to one e2e test, exceeding its timeout. LLM-B ",
                "frequently identifies the correct category (`test-reliability`) and a ",
                "near-correct component (`e2e test suite`, `regression`, `e2e-tests`). The ",
                "aligned matcher was tuned conservatively against `test-suite`; promoting ",
                "the synonyms above would *over-credit* F9 (where `regression` is wrong). ",
                "This is therefore a **matcher-calibration issue**, not an LLM diagnostic ",
                "failure: a venue-specific re-extension of the alias table would recover ",
                "these cells. Both *strict* and *aligned* numbers are reported throughout ",
                "the article so the reader can see the gap directly.",
                "",
            ]
        elif scenario == "F9":
            md += [
                "**Why this fails.** The injected fault corrupts the seed-data file (a ",
                "manifest generator), which makes the contract and e2e tests fail downstream. ",
                "LLM-A typically names `application` (fully symptom-blaming). LLM-B often ",
                "names the changed file (`scripts/generate_preview_manifest.py`) — meaning ",
                "the provenance link from `ChangedFile` to the failure *was* used — but it ",
                "assigns the wrong category (`configuration` instead of `database`). The ",
                "rubric tags F9 as `database` because the corrupted seed produces an ",
                "inconsistent DB state. This is a **taxonomy edge case** — both `database` ",
                "and `configuration` are defensible from the evidence alone, and ",
                "adjudicating against the rubric requires venue-specific category ",
                "definitions.",
                "",
            ]

    md += [
        "## What the three families have in common",
        "",
        "- The operator captures the relevant evidence in every case (the ChangedFile, the ",
        "  test results, the relevant pod logs, the Kubernetes events). The gap is **always ",
        "  downstream of capture** — in diagnoser ranking, matcher calibration, or taxonomy ",
        "  specification.",
        "- L4 (FailureReport + provenance graph) does not lift these cells above zero, but ",
        "  also is **not** *worse* than L3 here — the regression is bounded.",
        "- These three scenarios are the **future-work catalogue** (§7 of the article): ",
        "  ranking-aware diagnosers (C-a), expanded alias tables (C-b), refined category ",
        "  taxonomies (C-c).",
        "",
        "Source cards:",
    ]
    for c in parsed:
        rel = c["path"].relative_to(REPO)
        md.append(f"- `{rel}`")
    md.append("")

    (OUT / "failure-analysis.md").write_text("\n".join(md))
    print("wrote:", OUT / "failure-analysis.md")
    print(f"covered {len(parsed)} cards: {sorted(set(c.get('subject','') for c in parsed))} × F5/F9/F10")
    return 0


if __name__ == "__main__":
    sys.exit(main())
